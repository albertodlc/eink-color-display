# Measured Spectra 6 appearance, same order as kPhotoPalette in
# src/air_traffic.cpp.
PALETTE = [
    (0, 0, 0),        # black
    (245, 245, 240),  # white
    (60, 140, 75),    # green
    (40, 85, 180),    # blue
    (196, 50, 58),    # red
    (230, 200, 40),   # yellow
]

FLAG_W = 30
FLAG_H = 20
ROW_BYTES = (FLAG_W + 1) // 2


def nearest_index(rgb: tuple[int, int, int]) -> int:
    r, g, b = rgb
    best = 1
    best_distance = 1 << 32
    for index, (pr, pg, pb) in enumerate(PALETTE):
        distance = 3 * (r - pr) ** 2 + 4 * (g - pg) ** 2 + 2 * (b - pb) ** 2
        if distance < best_distance:
            best_distance = distance
            best = index
    return best


def load_flag(iso: str, cache_dir: pathlib.Path) -> Image.Image:
    cache_dir.mkdir(parents=True, exist_ok=True)
    path = cache_dir / f"{iso.lower()}.png"
    if not path.exists():
        url = f"https://flagcdn.com/w40/{iso.lower()}.png"
        request = urllib.request.Request(
            url, headers={"User-Agent": "eink-color-display/1.0"}
        )
        with urllib.request.urlopen(request, timeout=20) as response:
            path.write_bytes(response.read())
    return Image.open(path).convert("RGBA")


def render_flag(image: Image.Image) -> list[int]:
    image = image.convert("RGBA")
    width, height = image.size
    scale = min(FLAG_W / width, FLAG_H / height)
    resized = image.resize(
        (max(1, round(width * scale)), max(1, round(height * scale))),
        Image.Resampling.LANCZOS,
    )
    canvas = Image.new("RGBA", (FLAG_W, FLAG_H), PALETTE[1] + (255,))
    canvas.alpha_composite(
        resized, ((FLAG_W - resized.width) // 2, (FLAG_H - resized.height) // 2)
    )
    pixels = canvas.convert("RGB").load()

    packed: list[int] = []
    for y in range(FLAG_H):
        for x in range(0, FLAG_W, 2):
            low = nearest_index(pixels[x, y])
            high = nearest_index(pixels[x + 1, y]) if x + 1 < FLAG_W else 0
            packed.append(low | (high << 4))
    assert len(packed) == FLAG_H * ROW_BYTES
    return packed


def enum_name(iso: str) -> str:
    return f"kFlag{iso}"


def write_header(path: pathlib.Path, rows: dict[str, list[int]]) -> None:
    lines = [
        "// Generated by tools/make_flags.py. Do not edit by hand.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"constexpr uint8_t kFlagWidth = {FLAG_W};",
        f"constexpr uint8_t kFlagHeight = {FLAG_H};",
        f"constexpr uint8_t kFlagRowBytes = {ROW_BYTES};",
        f"constexpr uint16_t kFlagBytes = {FLAG_H * ROW_BYTES};",
        "",
        "enum FlagId : uint8_t {",
        "  kFlagNone = 0,",
    ]
    for iso, _ in FLAGS:
        lines.append(f"  {enum_name(iso)},")
    lines += [
        "  kFlagCount",
        "};",
        "",
        "const char* const kFlagNames[kFlagCount] = {",
        '    "",',
    ]
    for _, name in FLAGS:
        lines.append(f'    "{name}",')
    lines += [
        "};",
        "",
        f"const uint8_t kFlagData[kFlagCount][kFlagBytes] = {{",
        "    {0},  // kFlagNone",
    ]
    for iso, _ in FLAGS:
        values = rows[iso]
        lines.append(f"    {{  // {iso}")
        for start in range(0, len(values), 16):
            chunk = ", ".join(f"0x{value:02X}" for value in values[start : start + 16])
            lines.append(f"        {chunk},")
        lines.append("    },")
    lines += ["};", ""]
    path.write_text("\n".join(lines))
    print(f"wrote {path} ({len(FLAGS)} flags, {len(FLAGS) * len(rows[FLAGS[0][0]])} bytes)")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--cache",
        type=pathlib.Path,
        default=pathlib.Path("/tmp/opencode/flag-cache"),
        help="directory for downloaded flag PNGs",
    )
    parser.add_argument(
        "--output",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parent.parent / "src" / "flags.h",
    )
    args = parser.parse_args()

    rows = {iso: render_flag(load_flag(iso, args.cache)) for iso, _ in FLAGS}
    write_header(args.output, rows)


if __name__ == "__main__":
    main()

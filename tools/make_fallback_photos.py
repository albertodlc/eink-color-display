#!/usr/bin/env python3
"""Build the bundled fallback aircraft photos for the air-traffic poster.

The source photos live in assets/aircraft/ and are normal side-view photos.
They are cropped, enhanced and stored as smooth RGB332 data. The ESP32
bilinearly resamples that data to the card size and dithers it to the panel's
six inks at the final display resolution.

Requires: Pillow.
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageEnhance, ImageFilter, ImageFont


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "aircraft"
OUTPUT = ROOT / "src" / "fallback_photos.h"
PREVIEW = ROOT / "docs" / "fallback-photos-preview.png"

WIDTH = 480
HEIGHT = 192
PHOTO_BYTES = WIDTH * HEIGHT

# Same order as kPhotoPalette / kPhotoColors in src/air_traffic.cpp.
PALETTE = [
    (0, 0, 0),        # black
    (245, 245, 240),  # white
    (60, 140, 75),    # green
    (40, 85, 180),    # blue
    (196, 50, 58),    # red
    (230, 200, 40),   # yellow
]

SPECS = [
    ("A320", "a320.jpg"),
    ("B738", "b738.jpg"),
    ("B752", "b752.jpg"),
    ("A333", "a333.jpg"),
    ("AT72", "at72.jpg"),
    ("C172", "c172.jpg"),
    ("A139", "a139.jpg"),
    ("C25B", "c25b.jpg"),
    ("E190", "e190.jpg"),
    ("DH8D", "dh8d.jpg"),
]


def crop_to_card(image: Image.Image) -> Image.Image:
    """Centre-crop to the card aspect, then resize to 480x192."""
    scale = max(WIDTH / image.width, HEIGHT / image.height)
    size = (max(WIDTH, int(image.width * scale + 0.5)),
            max(HEIGHT, int(image.height * scale + 0.5)))
    image = image.resize(size, Image.Resampling.LANCZOS)
    left = (size[0] - WIDTH) // 2
    top = (size[1] - HEIGHT) // 2
    return image.crop((left, top, left + WIDTH, top + HEIGHT))


def enhance(image: Image.Image) -> Image.Image:
    """Lift saturation and contrast slightly before storing."""
    gamma = 0.98
    table = [
        min(255, int(round(255.0 * ((i / 255.0) ** gamma))))
        for i in range(256)
    ]
    image = image.point(table * 3)
    image = ImageEnhance.Color(image).enhance(1.05)
    image = ImageEnhance.Contrast(image).enhance(1.02)
    image = ImageEnhance.Brightness(image).enhance(1.02)
    return image.filter(ImageFilter.GaussianBlur(0.4))


def pack_rgb332(image: Image.Image) -> bytes:
    """Pack one byte per pixel: RRRGGGBB."""
    data = bytearray(PHOTO_BYTES)
    pixels = image.load()
    for y in range(HEIGHT):
        row = y * WIDTH
        for x in range(WIDTH):
            r, g, b = pixels[x, y]
            data[row + x] = ((r >> 5) << 5) | ((g >> 5) << 2) | (b >> 6)
    return bytes(data)


def preview_dither(image: Image.Image) -> Image.Image:
    """Approximate the firmware's output by dithering at the grid card size."""
    card = image.resize((375, 150), Image.Resampling.LANCZOS)
    palette = Image.new("P", (1, 1))
    flat: list[int] = []
    for colour in PALETTE:
        flat.extend(colour)
    flat.extend([0] * (768 - len(flat)))
    palette.putpalette(flat)
    return card.convert(
        "P", palette=palette, dither=Image.Dither.FLOYDSTEINBERG
    ).convert("RGB")


def header(entries: list[tuple[str, bytes]]) -> str:
    lines = [
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        "// Generated by tools/make_fallback_photos.py from assets/aircraft/.",
        "// RGB332 pixels; sources and licences: assets/aircraft/ATTRIBUTION.md.",
        f"static constexpr uint16_t kFallbackPhotoWidth = {WIDTH};",
        f"static constexpr uint16_t kFallbackPhotoHeight = {HEIGHT};",
        f"static constexpr uint32_t kFallbackPhotoBytes = {PHOTO_BYTES};",
        "",
    ]
    for name, data in entries:
        lines.append(
            f"static const uint8_t kFallback{name}[kFallbackPhotoBytes] "
            "PROGMEM = {"
        )
        for offset in range(0, len(data), 16):
            chunk = data[offset : offset + 16]
            lines.append("  " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
        lines.append("};")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    entries: list[tuple[str, bytes]] = []
    previews: list[tuple[str, Image.Image]] = []

    for name, filename in SPECS:
        image = Image.open(SOURCE / filename).convert("RGB")
        card = enhance(crop_to_card(image))
        entries.append((name, pack_rgb332(card)))
        previews.append((name, preview_dither(card)))

    OUTPUT.write_text(header(entries))

    font = ImageFont.truetype(
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 16
    )
    tile_w, tile_h = WIDTH + 20, HEIGHT + 34
    sheet = Image.new("RGB", (tile_w, tile_h * len(previews)), (255, 255, 255))
    draw = ImageDraw.Draw(sheet)
    for index, (name, image) in enumerate(previews):
        y = index * tile_h
        sheet.paste(image, (10, y + 26))
        draw.text((10, y + 4), name, font=font, fill=(180, 0, 0))
    sheet.save(PREVIEW)

    print(f"wrote {OUTPUT} ({PHOTO_BYTES} bytes/image, RGB332)")
    print(f"wrote {PREVIEW}")


if __name__ == "__main__":
    main()
